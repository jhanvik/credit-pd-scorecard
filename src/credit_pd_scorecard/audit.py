"""Data audit: facts about the raw data, written to reports/data_audit.md.

The audit looks at the WHOLE dataset (all 30,000 rows) but only reports
data-quality facts, and the target rate. Nothing here is used to choose a model
setting; those choices are made on the training split only.
"""
import pandas as pd

from credit_pd_scorecard import config
from credit_pd_scorecard.load_data import load_raw
from credit_pd_scorecard.report_utils import df_to_markdown


def audit(df: pd.DataFrame) -> dict:
    """Compute data-quality facts. Returns plain Python values and small tables."""
    feature_cols = [c for c in df.columns if c not in (config.ID_COL, config.TARGET)]
    n = len(df)
    n_default = int(df[config.TARGET].sum())

    code_tables = {}
    for col in ("SEX", "EDUCATION", "MARRIAGE"):
        counts = df[col].value_counts().sort_index()
        documented = config.DOCUMENTED_CODES[col]
        code_tables[col] = [
            {"code": int(code), "rows": int(cnt), "documented": int(code) in documented}
            for code, cnt in counts.items()
        ]

    pay_codes = []
    for col in config.PAY_COLS:
        vc = df[col].value_counts()
        pay_codes.append(
            {
                "column": col,
                "code_minus2": int(vc.get(-2, 0)),
                "code_0": int(vc.get(0, 0)),
                "undocumented_share": float(df[col].isin([-2, 0]).mean()),
            }
        )

    groups = df.groupby(feature_cols)[config.TARGET].agg(["size", "nunique"])
    dup_groups = groups[groups["size"] > 1]
    conflicting = dup_groups[dup_groups["nunique"] > 1]

    bills = df[config.BILL_COLS]
    return {
        "n_duplicate_feature_groups": len(dup_groups),
        "n_rows_in_duplicate_groups": int(dup_groups["size"].sum()),
        "n_conflicting_label_groups": len(conflicting),
        "n_rows_in_conflicting_groups": int(conflicting["size"].sum()),
        "n_rows": n,
        "n_cols": df.shape[1],
        "n_duplicate_ids": int(df[config.ID_COL].duplicated().sum()),
        "n_duplicate_feature_rows": int(df[feature_cols].duplicated().sum()),
        "n_missing_cells": int(df.isna().sum().sum()),
        "n_default": n_default,
        "default_rate": n_default / n,
        "imbalance_ratio": (n - n_default) / n_default,
        "code_tables": code_tables,
        "pay_codes": pay_codes,
        "n_rows_negative_bill": int((bills < 0).any(axis=1).sum()),
        "n_rows_bill_over_limit": int(bills.gt(df["LIMIT_BAL"], axis=0).any(axis=1).sum()),
        "n_rows_negative_payment": int((df[config.PAYAMT_COLS] < 0).any(axis=1).sum()),
        "ranges": df[["LIMIT_BAL", "AGE", "BILL_AMT1", "PAY_AMT1"]]
        .describe(percentiles=[0.5])
        .loc[["min", "50%", "max"]]
        .round(0)
        .astype(int),
        "dtypes": df.dtypes.astype(str).value_counts().to_dict(),
    }


def render_markdown(r: dict) -> str:
    """Turn the audit dictionary into a short markdown report."""
    lines = [
        "# Data audit",
        "",
        "Generated by `credit_pd_scorecard.audit`. Covers the full dataset; "
        "only data-quality facts and the overall target rate are reported.",
        "",
        "## Size and quality",
        f"- Rows: {r['n_rows']:,} | Columns: {r['n_cols']} | Column types: {r['dtypes']}",
        f"- Missing cells: {r['n_missing_cells']}",
        f"- Duplicate IDs: {r['n_duplicate_ids']}",
        f"- Rows whose features match an earlier row (ignoring ID and target): "
        f"{r['n_duplicate_feature_rows']} extra rows in {r['n_duplicate_feature_groups']} groups "
        f"({r['n_rows_in_duplicate_groups']} rows in total). Kept: identical profiles are "
        "plausible, e.g. all-zero balances.",
        f"- Of those groups, {r['n_conflicting_label_groups']} contain customers with "
        f"the same features but different outcomes ({r['n_rows_in_conflicting_groups']} rows): "
        "a small amount of label noise that no model can resolve.",
        "",
        "## Target",
        f"- Defaults: {r['n_default']:,} of {r['n_rows']:,} ({r['default_rate']:.2%}); "
        f"about {r['imbalance_ratio']:.1f} non-defaults per default",
        "",
        "## Category codes vs the UCI documentation",
    ]
    for col, rows in r["code_tables"].items():
        lines.append("")
        lines.append(f"**{col}**")
        lines.append("")
        lines.append("| Code | Rows | Documented? |")
        lines.append("|---|---|---|")
        for row in rows:
            flag = "yes" if row["documented"] else "**NO**"
            lines.append(f"| {row['code']} | {row['rows']:,} | {flag} |")

    lines += [
        "",
        "## Repayment-status columns: undocumented codes",
        "The description defines -1 (paid duly) and 1-9 (months late). "
        "The data also contains -2 and 0.",
        "",
        "| Column | Rows with -2 | Rows with 0 | Share of rows with -2 or 0 |",
        "|---|---|---|---|",
    ]
    for row in r["pay_codes"]:
        lines.append(
            f"| {row['column']} | {row['code_minus2']:,} | {row['code_0']:,} | "
            f"{row['undocumented_share']:.1%} |"
        )

    lines += [
        "",
        "## Amounts",
        f"- Rows with at least one negative BILL_AMT: {r['n_rows_negative_bill']:,}",
        f"- Rows where a bill exceeds the credit limit in some month: {r['n_rows_bill_over_limit']:,}",
        f"- Rows with a negative PAY_AMT: {r['n_rows_negative_payment']:,}",
        "",
        "Min / median / max of key columns (NT dollars, age in years):",
        "",
        df_to_markdown(r["ranges"].rename_axis("statistic"), float_fmt="{:,.0f}"),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    df = load_raw()
    result = audit(df)
    config.REPORTS.mkdir(parents=True, exist_ok=True)
    out = config.REPORTS / "data_audit.md"
    out.write_text(render_markdown(result))
    print(f"Rows {result['n_rows']:,} | default rate {result['default_rate']:.4f}")
    print(f"Undocumented EDUCATION/MARRIAGE codes, PAY -2/0 codes: see {out}")


if __name__ == "__main__":
    main()
